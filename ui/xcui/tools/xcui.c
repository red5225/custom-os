#include "xcui.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static char *read_file(const char *path) {
    FILE *f=fopen(path,"rb"); long size; char *data;
    if (!f) return NULL;
    if (fseek(f,0,SEEK_END)!=0) { fclose(f); return NULL; }
    size=ftell(f); if (size<0 || size>1024*1024) { fclose(f); return NULL; }
    rewind(f); data=(char*)malloc((size_t)size+1);
    if (!data) { fclose(f); return NULL; }
    if (fread(data,1,(size_t)size,f)!=(size_t)size) { free(data); fclose(f); return NULL; }
    data[size]='\0'; fclose(f); return data;
}
static void emit_string(FILE *out,const char *s) {
    const unsigned char *p=(const unsigned char*)s;
    fputc('"',out);
    while (*p) {
        if (*p=='"' || *p=='\\') { fputc('\\',out); fputc(*p,out); }
        else if (*p=='\n') fputs("\\n",out);
        else if (*p=='\r') fputs("\\r",out);
        else if (*p=='\t') fputs("\\t",out);
        else if (*p<32 || *p>126) fprintf(out,"\\%03o",(unsigned)*p);
        else fputc(*p,out);
        ++p;
    }
    fputc('"',out);
}
static int emit_c(const char *output, const struct xcui_tree *tree) {
    FILE *f = fopen(output, "wb");
    unsigned i;
    if (!f) { fprintf(stderr, "xcui: cannot write %s\n", output); return 2; }
    fputs("/* Generated by xcui. Compile this data with the XCUI runtime. */\n#include \"xcui.h\"\n\n", f);
    fputs("const struct xcui_tree xcui_embedded_tree = {\n", f);
    fprintf(f, "    .abi_version = %uu,\n    .node_count = %uu,\n    .app = ", (unsigned)tree->abi_version, (unsigned)tree->node_count);
    emit_string(f, tree->app);
    fputs(",\n    .nodes = {\n", f);
    for (i = 0; i < tree->node_count; ++i) {
        const struct xcui_node *n = &tree->nodes[i];
        fprintf(f, "        [%u] = { .kind=%uu, .parent=%uu, .first_child=%uu, .next_sibling=%uu,\n",
                i, (unsigned)n->kind, (unsigned)n->parent,
                (unsigned)n->first_child, (unsigned)n->next_sibling);
        fprintf(f, "            .x=%d, .y=%d, .width=%d, .height=%d, .declared_width=%d, .declared_height=%d,\n",
                n->x, n->y, n->width, n->height, n->declared_width, n->declared_height);
        fprintf(f, "            .padding=%uu, .gap=%uu, .font_size=%uu,\n",
                (unsigned)n->padding, (unsigned)n->gap, (unsigned)n->font_size);
        fprintf(f, "            .foreground=%uu, .background=%uu, .has_foreground=%uu, .has_background=%uu,\n",
                (unsigned)n->foreground, (unsigned)n->background,
                (unsigned)n->has_foreground, (unsigned)n->has_background);
        fputs("            .text = ", f); emit_string(f, n->text);
        fputs(", .action = ", f); emit_string(f, n->action);
        fputs(" },\n", f);
    }
    fputs("    }\n};\n", f);
    if (fclose(f) != 0) { fprintf(stderr, "xcui: failed closing %s\n", output); return 2; }
    return 0;
}
int main(int argc,char **argv) {
    char *source; struct xcui_tree *tree; struct xcui_error error; int result=0;
    if (argc<3 || (strcmp(argv[1],"check") && strcmp(argv[1],"build"))) {
        fprintf(stderr,"usage: xcui check file.xcui | xcui build file.xcui -o embedded_ui.c\n"); return 2;
    }
    source=read_file(argv[2]);
    if (!source) { fprintf(stderr,"xcui: cannot read %s (max 1 MiB)\n",argv[2]); return 2; }
    tree=(struct xcui_tree*)calloc(1,sizeof(*tree));
    if (!tree) { free(source); return 2; }
    if (!xcui_parse(source,tree,&error)) {
        fprintf(stderr,"xcui: line %u: %s\n",error.line,xcui_error_name(error.code)); result=1;
    } else if (!strcmp(argv[1],"check")) {
        printf("XCUI OK: app=\"%s\", %u node(s), ABI %u\n",tree->app,(unsigned)tree->node_count,(unsigned)tree->abi_version);
    } else if (argc==5 && !strcmp(argv[3],"-o")) {
        result=emit_c(argv[4],tree);
        if (!result) printf("XCUI embedded C source written: %s\n",argv[4]);
    } else {
        fprintf(stderr,"usage: xcui build file.xcui -o embedded_ui.c\n"); result=2;
    }
    free(tree); free(source); return result;
}
